// Operator Aritmatika
let a = 10;
let b = 3;
console.log("Operator Aritmatika:");
console.log("a + b =", a + b);
console.log("a - b =", a - b);
console.log("a * b =", a * b);
console.log("a / b =", a / b);
console.log("a % b =", a % b);
console.log("a ** b =", a ** b);

// Operator Penugasan
let c = 5;
console.log("\nOperator Penugasan:");
console.log("c =", c);
c += 2;
console.log("c += 2 =>", c);
c -= 1;
console.log("c -= 1 =>", c);
c *= 3;
console.log("c *= 3 =>", c);
c /= 2;
console.log("c /= 2 =>", c);

// Operator Perbandingan
console.log("\nOperator Perbandingan:");
console.log("10 == '10' =>", 10 == '10');
console.log("10 === '10' =>", 10 === '10');
console.log("10 != '10' =>", 10 != '10');
console.log("10 !== '10' =>", 10 !== '10');
console.log("5 > 3 =>", 5 > 3);
console.log("5 < 3 =>", 5 < 3);
console.log("5 >= 5 =>", 5 >= 5);
console.log("5 <= 4 =>", 5 <= 4);

// Operator Logika
console.log("\nOperator Logika:");
console.log("true && false =>", true && false);
console.log("true || false =>", true || false);
console.log("!true =>", !true);

// Operator Unary
let x = 5;
console.log("\nOperator Unary:");
console.log("x =", x);
console.log("++x =>", ++x);
console.log("x++ =>", x++);
console.log("x sekarang =>", x);
console.log("--x =>", --x);
console.log("x-- =>", x--);
console.log("x sekarang =>", x);

// Operator Ternary
let umur = 18;
console.log("\nOperator Ternary:");
console.log("umur >= 18 ? 'Dewasa' : 'Anak-anak' =>", umur >= 18 ? 'Dewasa' : 'Anak-anak');

// Operator Typeof
console.log("\nOperator Typeof:");
console.log("typeof 42 =>", typeof 42);
console.log("typeof 'hello' =>", typeof 'hello');
console.log("typeof true =>", typeof true);
console.log("typeof undefined =>", typeof undefined);
console.log("typeof null =>", typeof null);
console.log("typeof {} =>", typeof {});
